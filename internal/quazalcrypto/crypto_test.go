func unhex(t *testing.T, text string) []byte {
	t.Helper()
	data, err := hex.DecodeString(text)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func fixtureKey(start byte) (key Key) {
	for i := range key {
		key[i] = start + byte(i)
	}
	return key
}

// Independently calculated with Python hashlib, including the PID modulus
// boundaries. These constants are synthetic and contain no retail credentials.
func TestPasswordDerivationVectors(t *testing.T) {
	password := []byte("fixture-password")
	original := bytes.Clone(password)
	if got := InitialKey(password); hex.EncodeToString(got[:]) != "c81968fffd0d026311662b143b026fe2" {
		t.Fatalf("initial key %x", got)
	}
	for _, test := range []struct {
		pid  uint32
		want string
	}{
		{0, "c81968fffd0d026311662b143b026fe2"},
		{2, "e182b1fa7fcc16a0bcbe086b3e76170d"},
		{1023, "a5ec198befeb66f35f047b275c95a487"},
		{1024, "c81968fffd0d026311662b143b026fe2"},
		{0x12345678, "91eb59ad53d2a2ddfe7b07274d15b6ad"},
		{0xffffffff, "a5ec198befeb66f35f047b275c95a487"},
	} {
		got := PasswordKey(password, test.pid)
		if hex.EncodeToString(got[:]) != test.want {
			t.Fatalf("PID %x: %x", test.pid, got)
		}
		if got != ExtendInitial(InitialKey(password), test.pid) {
			t.Fatal("signup hash extension differs")
		}
	}
	if !bytes.Equal(password, original) {
		t.Fatal("derivation mutated password")
	}
}

// RC4 ciphertext independently generated by cryptography's ARC4 implementation;
// appended tags independently generated by Python hmac/hashlib.
func TestAuthenticatedContainerVectors(t *testing.T) {
	key := fixtureKey(0)
	tests := []struct{ plaintext, want string }{
		{"", "c91e40247251f39bdfe6a7b72a5857f9"},
		{"6669787475726520706c61696e74657874", "8ff5388d32907cec76b7f6af60a94f37a71786095560a71419b48391ada331f2a0"},
		{"000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f", "e99d42fa43e71fcb0ed29dcd02d02440c360934ce6a254f99787bfc2e52afd1dd3bdfce50b81c33cac6b3a01972cbeb2"},
	}
	for _, test := range tests {
		plaintext := unhex(t, test.plaintext)
		sealed := Seal(key, plaintext)
		if !bytes.Equal(sealed, unhex(t, test.want)) {
			t.Fatalf("container: %x", sealed)
		}
		got, err := Open(key, sealed)
		if err != nil || !bytes.Equal(got, plaintext) {
			t.Fatalf("open: %x, %v", got, err)
		}
		// Consecutive operations start at the same RC4 state, as the client does.
		if !bytes.Equal(Seal(key, plaintext), sealed) {
			t.Fatal("container leaked RC4 state")
		}
	}
}

func TestContainerTamperingAndInputOwnership(t *testing.T) {
	key := fixtureKey(0)
	plaintext := []byte("authenticated fixture with enough bytes")
	original := bytes.Clone(plaintext)
	sealed := Seal(key, plaintext)
	if !bytes.Equal(plaintext, original) {
		t.Fatal("seal mutated plaintext")
	}
	for i := range sealed {
		changed := bytes.Clone(sealed)
		changed[i] ^= 1
		got, err := Open(key, changed)
		if !errors.Is(err, ErrAuthentication) || got != nil {
			t.Fatalf("accepted altered byte %d: %x %v", i, got, err)
		}
	}
	for n := 0; n < TagSize; n++ {
		if got, err := Open(key, sealed[:n]); !errors.Is(err, ErrAuthentication) || got != nil {
			t.Fatalf("accepted short tag length %d", n)
		}
	}
	if got, err := Open(fixtureKey(1), sealed); !errors.Is(err, ErrAuthentication) || got != nil {
		t.Fatal("accepted wrong key")
	}
	input := bytes.Clone(sealed)
	got, err := Open(key, sealed)
	if err != nil {
		t.Fatal(err)
	}
	got[0] ^= 1
	if !bytes.Equal(sealed, input) {
		t.Fatal("open returned an alias")
	}
}
